package PageObjects;

import org.junit.After;
import org.junit.Before;
import org.junit.BeforeClass;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.junit.runners.Parameterized;
import org.openqa.selenium.WebDriver;
import org.openqa.selenium.chrome.ChromeDriver;
import org.openqa.selenium.chrome.ChromeOptions;
import static org.junit.Assert.assertEquals;

@RunWith(Parameterized.class)
public class FaqListTest {
    private WebDriver driver;
    private MainPage objMainPage;
    private static int currentI;
    private final String expectedQuestion;
    private final String expectedAnswer;

    public FaqListTest(String expectedQuestion, String expectedAnswer) {
        this.expectedQuestion = expectedQuestion;
        this.expectedAnswer = expectedAnswer;
    }

    @BeforeClass
    public static void resetCounter() {
        currentI = 0;
    }

    @Parameterized.Parameters
    public static Object[][] getQsAndAs() {
        return new Object[][]{
                {"Сколько это стоит? И как оплатить?", "Сутки — 400 рублей. Оплата курьеру — наличными или картой."},
                {"Хочу сразу несколько самокатов! Так можно?", "Пока что у нас так: один заказ — один самокат. Если хотите покататься с друзьями, можете просто сделать несколько заказов — один за другим."},
                {"Как рассчитывается время аренды?", "Допустим, вы оформляете заказ на 8 мая. Мы привозим самокат 8 мая в течение дня. Отсчёт времени аренды начинается с момента, когда вы оплатите заказ курьеру. Если мы привезли самокат 8 мая в 20:30, суточная аренда закончится 9 мая в 20:30."},
                {"Можно ли заказать самокат прямо на сегодня?", "Только начиная с завтрашнего дня. Но скоро станем расторопнее."},
                {"Можно ли продлить заказ или вернуть самокат раньше?", "Пока что нет! Но если что-то срочное — всегда можно позвонить в поддержку по красивому номеру 1010."},
                {"Вы привозите зарядку вместе с самокатом?", "Самокат приезжает к вам с полной зарядкой. Этого хватает на восемь суток — даже если будете кататься без передышек и во сне. Зарядка не понадобится."},
                {"Можно ли отменить заказ?", "Да, пока самокат не привезли. Штрафа не будет, объяснительной записки тоже не попросим. Все же свои."},
                {"Я жизу за МКАДом, привезёте?", "Да, обязательно. Всем самокатов! И Москве, и Московской области."}
        };
    }

    @Before
    public void setUp() {
        ChromeOptions options = new ChromeOptions();
        options.addArguments("--no-sandbox", "--headless", "--disable-dev-shm-usage");
        driver = new ChromeDriver(options);
        driver.get("https://qa-scooter.praktikum-services.ru/");

        objMainPage = new MainPage(driver);
        objMainPage.acceptCookies();
        objMainPage.scrollToFaqList();

    }

    @Test
    public void checkFaqListElementsText() {
        int i = currentI;
        String actualQuestion = objMainPage.getQuestionText(i);
        assertEquals("Wrong Question Text", expectedQuestion, actualQuestion);

        objMainPage.clickQuestion(i);

        String actualAnswer = objMainPage.getAnswerText(i);
        assertEquals("Wrong Answer Text", expectedAnswer, actualAnswer);


    }

    @After
    public void tearDown() {
        currentI++;
        driver.quit();

    }
}

